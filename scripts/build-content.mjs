// Builds www/js/content.js from the lessons in content/lessons/.
//
//   node scripts/build-content.mjs           build once
//   node scripts/build-content.mjs --watch   rebuild when a lesson changes
//
// The build stops on any lesson that breaks the rules (scripts/content.mjs),
// so a broken lesson never reaches the app.
import { watch, writeFileSync } from 'node:fs';
import { contentProblems, LESSONS_DIR, loadLessons } from './content.mjs';

const OUT = new URL('../www/js/content.js', import.meta.url).pathname;

function build() {
  const lessons = loadLessons();
  const problems = contentProblems(lessons);
  if (problems.length > 0) throw new Error(`content check failed:\n  - ${problems.join('\n  - ')}`);

  const app = {};
  for (const [locale, list] of Object.entries(lessons)) {
    app[locale] = list.map(({ structure, ...lesson }) => lesson);
  }
  writeFileSync(
    OUT,
    '// GENERATED by scripts/build-content.mjs from content/lessons/. Do not edit.\n' +
      `export const LESSONS = ${JSON.stringify(app)};\n`,
  );
  const counts = Object.entries(lessons).map(([locale, list]) => `${list.length} ${locale}`).join(', ');
  console.log(`content: ${counts} lessons -> www/js/content.js`);
}

function tryBuild() {
  try {
    build();
    return true;
  } catch (error) {
    console.error(error.message);
    return false;
  }
}

if (process.argv.includes('--watch')) {
  tryBuild();
  let timer;
  watch(LESSONS_DIR, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(tryBuild, 100);
  });
  console.log('watching content/lessons/ ...');
} else if (!tryBuild()) {
  process.exit(1);
}
